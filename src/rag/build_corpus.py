def has_final(word):
    """마지막 글자에 받침이 있는지 (한글이 아니면 숫자 발음으로 어림)"""
    ch = re.sub(r"[\s)\]'\"」』.]+$", "", word)[-1:]
    if "가" <= ch <= "힣":
        return (ord(ch) - 0xAC00) % 28 != 0
    return ch in "013678LMNlmn"


def josa(word, pair):
    """pair: '은는' '이가' '을를' '과와' '으로로'"""
    a, b = (pair[:2], pair[2:]) if pair == "으로로" else (pair[0], pair[1])
    return word + (a if has_final(word) else b)


def copula(word):
    """'~이에요/~예요'"""
    return word + ("이에요" if has_final(word) else "예요")


def age_text(age):
    lo, hi = age["min"], age["max"]
    if lo is None and hi is None:
        return "나이 제한 없음"
    if lo is not None and hi is not None:
        return f"만 {lo}세" if lo == hi else f"만 {lo}~{hi}세"
    return f"만 {lo}세 이상" if lo is not None else f"만 {hi}세 이하"


