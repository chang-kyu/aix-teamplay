def oos_chunks():
    out = []
    for oid, title, kw, examples, say, names, near in OOS:
        head = f"{title} | {SECTION_LABEL['oos']}"
        out.append({"id": oid, "policyId": None, "section": "oos", "unit": oid, "title": title,
                    "text": head + "\n- 낱말: " + ", ".join(kw + names), "say": say, "keywords": kw + names, "names": names, "near": near})
        for n, ex in enumerate(examples, 1):
            # embed: 의미 검색 벡터를 만들 때 쓰는 글(예시 질문 한 문장). 제목 줄을 빼야 질문과 더 가깝게 맞는다
            out.append({"id": f"{oid}#{n}", "policyId": None, "section": "oos", "unit": oid, "title": title,
                        "text": head + f"\n- 예: {ex}", "say": say, "embed": ex})
    return out


def build():
    data = json.loads((ROOT / "policies_v3.json").read_text(encoding="utf-8"))
    missing = [p["id"] for p in data["policies"] if p["id"] not in EXTRA]
    if missing:   # 자동 점검으로 새로 들어온 사업: 설명용 값 없이 policies_v3.json 값만으로 청크를 만든다
        print(f"! EXTRA 에 없는 사업 {len(missing)}건 (기본 정보로만 청크 생성): {missing}")
    chunks = []
    for p in data["policies"]:
        chunks += policy_chunks(p)
    chunks += help_chunks()
    chunks += oos_chunks()
    ids = [c["id"] for c in chunks]
    assert len(ids) == len(set(ids)), "청크 id 중복"
    policies_meta = {p["id"]: {"name": p["name"], "sourceUrl": p["sourceUrl"],
                               "sourceLabel": "안산시 고시·공고" if "selectBbsDetail" in p["sourceUrl"] else "안산시청 청년정책 페이지",
                               "kw": EXTRA.get(p["id"], {}).get("kw", []), "tags": EXTRA.get(p["id"], {}).get("tags", [])} for p in data["policies"]}
    return {"version": "v3-rag2", "asOf": data["asOf"], "policyCount": data["count"], "chunkCount": len(chunks),
            "sections": SECTION_LABEL, "policyMeta": policies_meta, "chunks": chunks}


