    if notes:
        add("notes", [re.sub(r"(이에요|예요|해요|있어요|없어요|돼요|됐어요|였어요)\.$", r"\1", n) for n in notes], " ".join(notes))

    # 공고 원문 전문 (rag/raw/{id}.txt 가 있을 때만). 소제목·빈 줄을 경계로 400자 안팎씩 자른다. 글은 고치지 않는다
    raw = RAW_DIR / f"{pid}.txt"
    if raw.exists():
        body = "\n".join(l for l in raw.read_text(encoding="utf-8").split("\n") if not l.startswith("#")).strip()
        parts, cur = [], ""
        for line in body.split("\n"):
            if cur and (len(cur) + len(line) > 400 or re.match(r"^(\d+\.|[가-하]\.|[○□■◆▶]|\[첨부)", line)) and len(cur) > 120:
                parts.append(cur.strip()); cur = ""
            cur += line + "\n"
        if cur.strip():
            parts.append(cur.strip())
        for n, part in enumerate(parts, 1):
            out.append({"id": f"{pid}#full{n}", "policyId": pid, "section": "full",
                        "text": f"{name} | 공고 원문 {n}/{len(parts)}\n{part}", "say": "공고 원문에는 이렇게 적혀 있어요: " + (part if len(part) <= 300 else part[:300] + "…"), "quote": part[:200]})
    return out


