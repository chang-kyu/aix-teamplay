def policy_chunks(p):
    x = EXTRA.get(p["id"], {})
    name, pid = p["name"], p["id"]
    res_line, res_say = residence_text(p["residence"])
    age_line = age_text(p["age"])
    others = p["otherConditions"]
    out = []

    def add(section, lines, say, quote=None, thin=False):
        c = {"id": f"{pid}#{section}", "policyId": pid, "section": section,
             "text": f"{name} | {SECTION_LABEL[section]}\n" + "\n".join(f"- {l}" for l in lines), "say": say}
        if quote:
            c["quote"] = quote
        if thin:
            c["thin"] = True
        out.append(c)

    # 개요
    add("overview",
        [f"분야: {p['category']}", f"한 줄 요약: {p['benefit']}", f"대상: {age_line}, {res_line}"]
        + ([f"조건: {' / '.join(others)}"] if others else []),
        f"{josa(name, '은는')} {p['category']} 분야 사업이에요. {p['benefit']}. 대상은 {age_line}, 거주 조건은 '{p['residence']['label']}'{'이에요' if has_final(p['residence']['label']) else '예요'}.")

    # 지원 대상
    lines = [f"나이: {age_line}", f"거주: {res_line}"]
    say = (f"나이 조건은 {copula(age_line)}. " if p["age"]["min"] is not None or p["age"]["max"] is not None else "나이 제한은 없어요. ") + res_say
    if others:
        lines.append("그 밖의 조건(본인 확인): " + " / ".join(others))
        say += " 그 밖에 " + ", ".join(f"'{o}'" for o in others) + " 조건은 직접 확인해 주세요."
    if p.get("bonus"):
        lines.append(f"가점·우대: {p['bonus']['text']}")
        say += f" 가점·우대: {p['bonus']['text']}."
    has_quote = not p["evidence"].startswith("(원문에")
    if has_quote:
        lines.append(f"공고 원문: \"{p['evidence']}\"")
    add("target", lines, say, quote=p["evidence"] if has_quote else None)

    # 지원 내용
    lines = [f"내용: {p['benefit']}"]
    say = f"지원 내용은 '{p['benefit']}'{'이에요' if has_final(p['benefit']) else '예요'}."
    seen = set(words(p["benefit"]))
    if x.get("detail") and set(words(x["detail"])) - seen:          # 상세에 새 정보가 있을 때만
        lines.append(f"상세: {x['detail']}")
        say += f" 상세: {x['detail']}."
        seen |= set(words(x["detail"]))
    if x.get("amount"):
        lines.append(f"금액: {x['amount']}")
        if set(words(x["amount"])) - seen:
            say += f" 금액은 {copula(x['amount'])}."
    add("benefit", lines, say)

    # 신청 기간
    a = p["apply"]
    lines, say = [], ""
    if a["start"] or a["end"]:
        span = f"{dot(a['start']) or '?'} ~ {dot(a['end']) or ''}".strip()
        lines.append(f"접수 기간: {span}")
        say = f"수집한 공고의 접수 기간은 {span}{'이에요' if a['end'] else ' (마감일 없음)이에요'}."
    if a["periodText"]:
        lines.append(f"안내: {a['periodText']}")
        say += (" " if say else "") + f"안내: {a['periodText']}."
    if x.get("notices"):
        lines.append("관련 공고: " + ", ".join(x["notices"]))
    if not lines:
        lines, say = ["접수 기간: 수집한 자료에 날짜가 없음(공고문에서 확인)"], "수집한 자료에는 접수 날짜가 없어요. 안산시청 원문에서 확인해 주세요."
    add("period", lines, say, thin=not (a["start"] or a["end"] or a["periodText"]))

    # 신청 방법
    lines, say_parts = [], []
    if x.get("method"):
        lines.append(f"신청 방법: {x['method']}")
        say_parts.append(f"신청 방법은 '{x['method']}'{'이에요' if has_final(x['method']) else '예요'}.")
    host = host_of(a["url"])
    if host and host != "ansan.go.kr":
        site, login = SITES.get(host, (host, False))
        lines.append(f"신청 사이트: {site} ({a['url']})" + (", 로그인 필요" if login else ""))
        lines.append(f"찾는 법: {'로그인한 뒤 ' if login else ''}검색창에 '{search_word(name)}' 검색 (사이트 첫 화면으로 열림)")
        say_parts.append(f"신청 사이트는 {copula(site)}. 첫 화면이 열리니 {'로그인한 뒤 ' if login else ''}검색창에 '{search_word(name)}'{'을' if has_final(search_word(name)) else '를'} 검색해 주세요.")
    elif host == "ansan.go.kr":
        lines.append(f"신청 사이트: 안산시청 누리집 ({a['url']})")
        say_parts.append("안산시청 누리집에서 신청해요.")
    thin = not lines
    if thin:
        lines = ["신청 방법: 수집한 자료에 없음(공고문에서 확인)"]
